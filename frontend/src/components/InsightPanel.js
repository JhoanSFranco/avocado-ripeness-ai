import React from 'react';

/** Natural-language advice (LLM-generated or rule-based fallback). */
export default function InsightPanel({ insight }) {
  if (!insight) return null;

  return (
    <section className="insight">
      <h4 className="section-title">{insight.title}</h4>
      <p className="text">{insight.summary}</p>
      <p className="text">
        <strong>Recommendation:</strong> {insight.recommendation}
      </p>
      <p className="text">
        <strong>Shelf life:</strong> {insight.shelf_life}
      </p>
      {insight.alert && <div className="alert">{insight.alert}</div>}
      {insight.actions?.length > 0 && (
        <ul className="insight__actions">
          {insight.actions.map((action) => (
            <li key={action}>{action}</li>
          ))}
        </ul>
      )}
      <p className="insight__source">
        {insight.source === 'llm' ? 'Generated by an LLM' : 'Generated from built-in rules'}
      </p>
    </section>
  );
}
